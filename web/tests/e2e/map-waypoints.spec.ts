import { expect, test } from '@playwright/test'
import { mockApi, setupRoute, saveRoute, useRoute } from './mocks'
test.use({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true })

test('switching POI category removes old map icons while the next result is pending', async ({ page }) => {
  await mockApi(page)
  let finish: (() => Promise<void>) | undefined
  await page.route('**/api/pois/corridor', async route => {
    if (route.request().postDataJSON().category === '药店') return route.fallback()
    await new Promise<void>(resolve => { finish = async () => {
      await route.fulfill({ json: { traceId: 'new-poi', mode: 'live', sourceKind: 'api-cache', warnings: [],
        retrieval: { queryTerms: ['超市'], category: '超市', windows: 1, pages: 1, rawCount: 1, uniqueCount: 1, truncated: false, sourceKind: 'derived' },
        pois: [{ place: { uid: 'new-shop', name: '新超市', coord: { lng: 116.35, lat: 40.08, crs: 'BD09' }, source: 'api-cache' }, distanceToRouteM: 10 }] } })
      resolve()
    } })
  })
  await setupRoute(page)
  const map = page.locator('.baidu-map__container')
  await expect(map.getByRole('button', { name: '测试药店', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '购物', exact: true }).click()
  await expect(map.getByRole('button', { name: '测试药店', exact: true })).toHaveCount(0)
  await expect.poll(() => Boolean(finish)).toBe(true)
  await finish!()
  await expect(map.getByRole('button', { name: '新超市', exact: true })).toBeVisible()
  await expect(map.getByRole('button', { name: '测试药店', exact: true })).toHaveCount(0)
})

test('clicking a map POI requests its route directly and can confirm it as a waypoint', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  const map = page.locator('.baidu-map__container')
  await expect(map.getByRole('button', { name: '测试药店', exact: true })).toBeVisible()
  const requests: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) requests.push(new URL(request.url()).pathname) })
  const request = page.waitForRequest(request => new URL(request.url()).pathname === '/api/routes/walking')
  await map.getByRole('button', { name: '测试药店', exact: true }).click()
  expect((await request).postDataJSON().destination).toMatchObject({ lng: 116.345, lat: 40.08, crs: 'BD09' })
  const card = page.getByRole('region', { name: '地图地点路线' })
  await expect(card).toContainText('步行 20分')
  expect(requests.filter(path => path === '/api/routes/walking')).toHaveLength(1)
  expect(requests).not.toContain('/api/isochrones')
  expect(requests).not.toContain('/api/pois/corridor/evidence')
  await card.getByRole('button', { name: '添加途经点', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择途经点' })
  await expect(picker.getByLabel('途经点名称')).toHaveValue('测试药店')
  await picker.getByRole('button', { name: '确认途经点' }).click()
  await expect(page.locator('.waypoints__place')).toContainText('测试药店')
})

test('waypoints can be dragged, moved with buttons, replaced, saved and planned in the displayed order', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  for (const name of ['取件', '买菜']) {
    await page.getByRole('button', { name: '＋ 添加途经点', exact: true }).click()
    const picker = page.getByRole('dialog', { name: '选择途经点' })
    await picker.getByLabel('搜索途经点').fill(name)
    await picker.getByRole('button', { name: '搜索', exact: true }).click()
    await picker.getByRole('button', { name: '选择 ' + name + '候选', exact: true }).click()
    await picker.getByRole('button', { name: '确认途经点' }).click()
  }
  await page.getByRole('button', { name: '上移途经点 买菜候选' }).click()
  await expect(page.locator('.waypoints__place strong')).toHaveText(['买菜候选', '取件候选'])
  const handle = page.getByRole('button', { name: '拖动途经点 买菜候选' })
  await handle.scrollIntoViewIfNeeded()
  const from = await handle.boundingBox()
  const to = await page.locator('.waypoints__row').nth(1).boundingBox()
  expect(from && to).toBeTruthy()
  await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2)
  await page.mouse.down()
  await page.mouse.move(from!.x + from!.width / 2, to!.y + to!.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect(page.locator('.waypoints__place strong')).toHaveText(['取件候选', '买菜候选'])
  const sent = page.waitForRequest(request => new URL(request.url()).pathname === '/api/plans')
  await page.getByRole('button', { name: '安排路线' }).click()
  const tasks = (await sent).postDataJSON().tasks
  expect(tasks[1].precedenceIds).toContain(tasks[0].id)
  await page.reload()
  await expect(page.locator('.waypoints__place strong')).toHaveText(['取件候选', '买菜候选'])
  await saveRoute(page, '途经顺序路径')
  await page.getByRole('button', { name: '反向路径' }).click()
  await expect(page.locator('.waypoints__place strong')).toHaveText(['买菜候选', '取件候选'])
  await useRoute(page, '途经顺序路径')
  await expect(page.locator('.waypoints__place strong')).toHaveText(['取件候选', '买菜候选'])
  await page.locator('.waypoints__place').first().click()
  const picker = page.getByRole('dialog', { name: '选择途经点' })
  await picker.getByLabel('搜索途经点').fill('书店')
  await picker.getByRole('button', { name: '搜索', exact: true }).click()
  await picker.getByRole('button', { name: '选择 书店候选', exact: true }).click()
  await picker.getByRole('button', { name: '确认途经点' }).click()
  await expect(page.locator('.waypoints__place strong')).toHaveText(['书店候选', '买菜候选'])
  await page.getByRole('button', { name: '删除途经点 买菜候选' }).click()
  await expect(page.locator('.waypoints__place strong')).toHaveText(['书店候选'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})
