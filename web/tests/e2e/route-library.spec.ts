import { expect, test } from '@playwright/test'
import { mockApi, setupRoute } from './mocks'

test.use({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true })

test('reversing a planned path clears the old arrival and execution state', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await page.locator('.poi-main').first().click()
  await page.getByRole('button', { name: '加入今天安排', exact: true }).click()
  await page.locator('.plan-bar').click()
  await page.getByRole('button', { name: '规划行程', exact: true }).click()
  await page.getByRole('button', { name: '预演行程', exact: true }).click()
  await page.getByRole('button', { name: '关闭今天行程', exact: true }).click()
  await expect(page.locator('.plan-bar')).toContainText('到达终点')
  await page.getByRole('button', { name: '反向路径', exact: true }).click()
  await expect(page.locator('.plan-bar')).toContainText('待规划')
  await expect(page.locator('.shell__clock-sub')).toHaveCount(0)
})

test('arbitrary places and saved paths persist; reversal sends the opposite direction', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await expect(page.locator('.poi-main').first()).toBeVisible()
  await page.locator('.endpoint').first().click()
  await page.getByRole('textbox', { name: '搜索地点', exact: true }).fill('图书馆')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.locator('.endpoint-picker__save > summary').click()
  await page.getByRole('textbox', { name: '地点名称', exact: true }).fill('阅读地点')
  await page.getByRole('button', { name: '保存地点 图书馆候选', exact: true }).click()
  await expect(page.getByRole('button', { name: '阅读地点', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog', { name: '选择起点', exact: true })).toBeVisible()
  await page.locator('.result').filter({ hasText: '图书馆候选' }).first().click()
  await expect(page.locator('.endpoint').first()).toContainText('图书馆候选')
  await expect(page.locator('.poi-main').first()).toBeVisible()
  await page.getByRole('button', { name: '我的路径', exact: true }).click()
  await page.getByRole('textbox', { name: '路径名称', exact: true }).fill('阅读之后')
  await page.getByRole('button', { name: '保存路径', exact: true }).click()
  await expect(page.locator('.results')).toContainText('阅读之后')
  const reversed = page.waitForRequest(r => r.method() === 'POST' && new URL(r.url()).pathname === '/api/routes/walking')
  await page.getByRole('button', { name: '反向路径', exact: true }).click()
  const payload = (await reversed).postDataJSON()
  expect(payload.origin.lng).toBe(116.33)
  expect(payload.destination.lng).toBe(116.34)
  await expect(page.locator('.endpoint').first()).toContainText('龙泽苑')
  await expect(page.locator('.endpoint').nth(1)).toContainText('图书馆候选')
  await page.locator('.result').filter({ hasText: '阅读之后' }).click()
  await expect(page.locator('.endpoint').first()).toContainText('图书馆候选')
  await page.reload()
  await page.getByRole('button', { name: '我的路径', exact: true }).click()
  await expect(page.locator('.results')).toContainText('阅读之后')
  await page.locator('.endpoint').first().click()
  await expect(page.getByRole('button', { name: '阅读地点', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭地点选择', exact: true }).click()
  await page.getByRole('button', { name: '我的路径', exact: true }).click()
  await page.getByRole('button', { name: '删除路径 阅读之后', exact: true }).click()
  await expect(page.locator('.results')).not.toContainText('阅读之后')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})

test('map creation can be cancelled without changing the selected endpoints', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await expect(page.locator('.poi-main').first()).toBeVisible()
  const before = await page.locator('.endpoint').first().textContent()
  await page.locator('.endpoint').first().click()
  await page.getByRole('button', { name: '地图选位置', exact: true }).click()
  await expect(page.getByRole('button', { name: '取消选点', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '取消选点', exact: true }).click()
  await expect(page.getByRole('button', { name: '取消选点', exact: true })).toHaveCount(0)
  await expect(page.locator('.endpoint').first()).toHaveText(before!)
})
