import { expect, test } from '@playwright/test'
import { mockApi, setupRoute } from './mocks'
test.use({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true })

test('adding a task returns from map picking, keeps the draft and supports searching a second place', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await expect(page.locator('.poi-main').first()).toBeVisible()
  await page.locator('.plan-bar').click()
  const dialog = page.getByRole('dialog', { name: '今天安排' })
  await dialog.getByText('添加地点', { exact: true }).click()
  await dialog.getByLabel('任务地点名称', { exact: true }).fill('取件')
  await dialog.getByRole('button', { name: '地图选点', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.shell__map')).toHaveCSS('min-height', /.+/)
  await page.locator('.baidu-map__container').click({ position: { x: 80, y: 200 } })
  await expect(page.getByLabel('所选地点名称')).toHaveValue('构造验收地址')
  await page.getByRole('button', { name: '确认位置', exact: true }).click()
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('任务地点名称', { exact: true })).toHaveValue('取件')
  await dialog.getByRole('button', { name: '加入安排', exact: true }).click()
  await expect(dialog.locator('.plan-panel__task')).toContainText('取件')
  await expect(dialog.locator('.plan-panel__task-detail')).toHaveCount(0)
  await dialog.getByLabel('搜索任务地点').fill('书店')
  await dialog.getByRole('button', { name: '搜索', exact: true }).click()
  await dialog.getByRole('button', { name: '选择 书店候选', exact: true }).click()
  await dialog.getByRole('button', { name: '加入安排', exact: true }).click()
  await expect(dialog.locator('.plan-panel__tasks')).toContainText('书店候选')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})

test('address lookup failure allows a named point and cancel does not create a place', async ({ page }) => {
  await mockApi(page)
  await page.route('**/api/locations/resolve', route => route.fulfill({ status: 503, json: { error: { message: '暂时无法查询地址' } } }))
  await setupRoute(page)
  await page.getByRole('button', { name: '我的地点', exact: true }).click()
  await page.getByRole('button', { name: '地图创建', exact: true }).click()
  await page.locator('.baidu-map__container').click({ position: { x: 80, y: 200 } })
  await expect(page.getByText('暂时无法查询地址', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认位置', exact: true })).toBeDisabled()
  await page.getByLabel('所选地点名称').fill('自选位置')
  await page.getByRole('button', { name: '确认位置', exact: true }).click()
  await expect(page.getByRole('button', { name: '将 自选位置 设为起点' })).toBeVisible()
  await page.getByRole('button', { name: '地图创建', exact: true }).click()
  await page.locator('.baidu-map__container').click({ position: { x: 80, y: 200 } })
  await page.locator('.baidu-map__pick-actions').getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.baidu-map__pick-banner')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '将 自选位置 设为起点' })).toHaveCount(1)
})

test('community map selection returns the resolved center without automatically measuring a circle', async ({ page }) => {
  await mockApi(page)
  let circles = 0
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/isochrones') circles++ })
  await page.goto('/community')
  await page.locator('.shell__search').click()
  await page.getByRole('button', { name: '地图选位置', exact: true }).click()
  await expect(page.locator('.sheet__content')).toBeHidden()
  await page.locator('.baidu-map__container').click({ position: { x: 80, y: 200 } })
  await expect(page.getByLabel('所选地点名称')).toHaveValue('构造验收地址')
  await page.getByRole('button', { name: '确认位置', exact: true }).click()
  await expect(page.locator('.origin-name')).toHaveText('构造验收地址')
  await expect(page.getByRole('button', { name: '设施社区评分', exact: true })).toBeEnabled()
  expect(circles).toBe(0)
  await page.locator('.shell__search').click()
  await page.getByRole('button', { name: '地图选位置', exact: true }).click()
  await page.getByRole('button', { name: '取消选点', exact: true }).click()
  await expect(page.locator('.origin-name')).toHaveText('构造验收地址')
})

test('choosing a route point and saving it are separate deliberate actions', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await expect(page.locator('.endpoint').first()).toContainText('回龙观小区')
  await page.locator('.endpoint').first().click()
  await page.getByRole('button', { name: '地图选位置', exact: true }).click()
  await page.locator('.baidu-map__container').click({ position: { x: 80, y: 200 } })
  await expect(page.getByLabel('所选地点名称')).toHaveValue('构造验收地址')
  await page.getByRole('button', { name: '确认位置', exact: true }).click()
  await expect(page.locator('.endpoint').first()).toContainText('构造验收地址')
  await page.getByRole('button', { name: '我的地点', exact: true }).click()
  await expect(page.getByRole('button', { name: '将 构造验收地址 设为起点' })).toHaveCount(0)
  await page.getByRole('button', { name: '保存当前起点', exact: true }).click()
  await expect(page.getByRole('button', { name: '将 构造验收地址 设为起点' })).toBeVisible()
})
