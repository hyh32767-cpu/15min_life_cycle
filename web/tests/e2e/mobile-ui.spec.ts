import { expect, test } from '@playwright/test'
import { mockApi, setupRoute, openPlan } from './mocks'

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })

test('mobile sheet expands, shrinks, and switches pages without retaining expansion', async ({ page }) => {
  await mockApi(page)
  await page.goto('/')
  await expect(page.locator('.plan-bar')).toHaveCount(0)
  await expect(page.locator('.sheet .shell__nav')).toBeVisible()
  await expect(page.locator('.sheet .shell__search-row')).toBeVisible()
  await expect(page.locator('.shell > .shell__omni')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '重新开始', exact: true })).toHaveCount(0)
  const sheet = page.locator('.sheet')
  const handle = page.getByRole('button', { name: '展开或收起面板' })
  const before = await sheet.boundingBox()
  await handle.click()
  await expect(handle).toHaveAttribute('aria-expanded', 'true')
  await expect.poll(async () => (await sheet.boundingBox())!.height).toBeGreaterThan(before!.height + 50)
  await page.getByRole('link', { name: '生活圈' }).click()
  await expect(handle).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('.shell__search')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

test('mobile plan modal traps focus, closes with Escape and restores the launcher', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await page.getByRole('button', { name: '买药', exact: true }).click()
  await page.locator('.poi-main').first().click()
  const launcher = page.getByRole('button', { name: '查看行程', exact: true })
  await page.getByRole('button', { name: '加入今天安排', exact: true }).click()
  await openPlan(page)
  const dialog = page.getByRole('dialog', { name: '今天安排' })
  const close = dialog.getByRole('button', { name: '关闭今天安排' })
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '预演行程', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(launcher).toBeFocused()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
})

test('empty service input does not silently replace the task duration with zero', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await page.getByRole('button', { name: '买药', exact: true }).click()
  await page.locator('.poi-main').first().click()
  await page.getByRole('button', { name: '加入今天安排', exact: true }).click()
  await openPlan(page)
  const dialog = page.getByRole('dialog', { name: '今天安排' })
  await dialog.getByRole('spinbutton').first().fill('')
  await dialog.getByRole('spinbutton').first().press('Tab')
  await expect(dialog.getByText('请填写停留分钟，填 0 表示不停留')).toBeVisible()
  await dialog.getByRole('spinbutton').first().fill('8')
  await dialog.getByRole('spinbutton').first().press('Tab')
  const requestPromise = page.waitForRequest((request) => request.method() === 'POST' && new URL(request.url()).pathname === '/api/plans')
  await dialog.getByRole('button', { name: '规划行程', exact: true }).click()
  const request = await requestPromise
  expect(request.postDataJSON().tasks[0].options[0].serviceSeconds).toBe(480)
})
