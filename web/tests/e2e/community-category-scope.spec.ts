import { expect, test } from '@playwright/test'
import { mockApi } from './mocks'

test('elderly zero coverage is not masked by shopping, and simulated additions use only elderly evidence', async ({ page }) => {
  await mockApi(page)
  await page.route('**/api/pois/corridor', route => {
    const body = route.request().postDataJSON()
    const pois = body.category === '养老' ? [] : Array.from({ length: 5 }, (_, i) => ({ place: {
      uid: `${body.category}-${i}`, name: `${body.category}设施${i}`, source: 'synthetic-assumption',
      coord: { lng: 116.36 + i * .001, lat: 40.09, crs: 'BD09' },
    }, distanceToRouteM: i * 100 }))
    return route.fulfill({ json: { pois, retrieval: { truncated: false }, warnings: [] } })
  })
  await page.goto('/community')
  await page.locator('.shell__search').click()
  await page.getByRole('searchbox').fill('回龙观')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('button', { name: '选择 回龙观小区', exact: true }).click()
  const checked = page.waitForRequest(r => r.url().endsWith('/api/community/coverage'))
  await page.getByRole('button', { name: '设施社区评分', exact: true }).click()
  const sampleCount = (await checked).postDataJSON().gridIds.length
  expect(sampleCount).toBeGreaterThan(9)
  expect(sampleCount).toBeLessThanOrEqual(25)
  await expect(page.getByText('7/7 已完成')).toBeVisible()
  await expect(page.locator('.scorecard__ring strong')).toHaveText('86')
  const simulationDownload = page.waitForEvent('download')
  if (!await page.locator('.community-tools').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.community-tools > summary').click()
  await page.getByRole('button', { name: '导出报告', exact: true }).click()
  const simulationStream = await (await simulationDownload).createReadStream()
  let simulationContent = ''
  for await (const chunk of simulationStream!) simulationContent += chunk.toString()
  const report = JSON.parse(simulationContent)
  expect(report.summary.averageCoveragePercent).toBe(86)
  expect(report.services.find((service: { id: string }) => service.id === 'elderly').baseline.coveredCount).toBe(0)
  expect(report.simulation).toBeNull()
  if (!await page.locator('.community-charts').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.community-charts > summary').click()
  await expect(page.getByRole('img', { name: /服务覆盖雷达图/ })).toHaveAttribute('aria-label', /养老0%/)
  await expect(page.locator('.coverage-radar__value')).toHaveCount(1)
  await expect(page.getByRole('button', { name: '查看养老覆盖' })).toHaveAttribute('aria-pressed', 'true')
  if (!await page.locator('.coverage-details').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.coverage-details > summary').click()
  await expect(page.locator('.summary .big')).toContainText(`覆盖 0/${sampleCount} · 0%`)
  await page.getByRole('button', { name: '查看建议', exact: true }).click()
  await expect(page.locator('.mclp-card')).toContainText(`养老仍有 ${sampleCount} 个采样点未覆盖`)
  await expect(page.locator('.mclp-card')).toContainText('本次没有可评估的候选位置')
  await page.getByRole('button', { name: '查看未覆盖位置', exact: true }).click()
  await expect(page.getByRole('img', { name: '未覆盖采样点', exact: true })).toHaveCount(sampleCount)
  await expect(page.locator('.baidu-map__legend')).toHaveCount(0)
  await page.getByRole('button', { name: '查看便利店覆盖' }).click()
  if (!await page.locator('.coverage-details').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.coverage-details > summary').click()
  await expect(page.getByRole('heading', { name: '便利店覆盖详情' })).toBeVisible()
  if (!await page.locator('.coverage-details').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.coverage-details > summary').click()
  await expect(page.locator('.summary .big')).toContainText(`覆盖 ${sampleCount}/${sampleCount} · 100%`)
  await page.getByRole('button', { name: '查看养老覆盖' }).click()
  await page.getByText('模拟新增设施', { exact: true }).click()
  await page.getByRole('textbox', { name: '搜索新增设施位置' }).fill('模拟养老中心')
  await page.locator('.card--sim').getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('button', { name: '选择 模拟养老中心候选', exact: true }).click()
  const request = page.waitForRequest(r => r.url().endsWith('/api/community/coverage') && !!r.postDataJSON().newFacilityId)
  await page.getByRole('button', { name: '新增并对比' }).click()
  const body = (await request).postDataJSON()
  expect(body.facilityIds).toEqual([])
  expect(body.times).toEqual([])
  expect(body.newFacilityTimes).toHaveLength(sampleCount)
  await expect(page.locator('.delta')).toHaveText(`新增前后：0 → ${sampleCount}`)
  await expect(page.locator('.scorecard__ring strong')).toHaveText('86')
  const repeated = page.waitForRequest(r => r.url().endsWith('/api/community/coverage') && !!r.postDataJSON().newFacilityId)
  await page.getByPlaceholder('模拟设施名称', { exact: true }).fill('另一处模拟设施')
  await page.getByRole('button', { name: '新增并对比' }).click()
  expect((await repeated).postDataJSON().newFacilityTimes).toHaveLength(sampleCount)
  await expect(page.locator('.delta')).toHaveText(`新增前后：0 → ${sampleCount}`)
  const afterSimulation = page.waitForEvent('download')
  if (!await page.locator('.community-tools').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.community-tools > summary').click()
  await page.getByRole('button', { name: '导出报告', exact: true }).click()
  const afterStream = await (await afterSimulation).createReadStream()
  let afterContent = ''
  for await (const chunk of afterStream!) afterContent += chunk.toString()
  const afterReport = JSON.parse(afterContent)
  expect(afterReport.summary.averageCoveragePercent).toBe(86)
  expect(afterReport.services.find((service: { id: string }) => service.id === 'elderly').baseline.coveredCount).toBe(0)
  expect(afterReport.simulation.name).toBe('另一处模拟设施')
  expect(afterReport.simulation.result.delta).toEqual({ before: 0, after: sampleCount })
  expect(afterReport.simulation.changesBaseline).toBe(false)
  await page.getByRole('button', { name: '查看便利店覆盖' }).click()
  await expect(page.locator('.delta')).toHaveCount(0)
  if (!await page.locator('.coverage-details').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.coverage-details > summary').click()
  await expect(page.locator('.summary .big')).toContainText(`覆盖 ${sampleCount}/${sampleCount} · 100%`)
})

test('empty truncated elderly retrieval remains unknown and does not generate a complete radar or score', async ({ page }) => {
  await mockApi(page)
  await page.route('**/api/pois/corridor', route => {
    const body = route.request().postDataJSON()
    return route.fulfill({ json: { pois: body.category === '养老' ? [] : [{ place: {
      uid: body.category, name: body.category, source: 'synthetic-assumption', coord: { lng: 116.36, lat: 40.09, crs: 'BD09' },
    }, distanceToRouteM: 0 }], retrieval: { truncated: body.category === '养老' }, warnings: [] } })
  })
  await page.goto('/community')
  await page.locator('.shell__search').click()
  await page.getByRole('searchbox').fill('回龙观')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('button', { name: '选择 回龙观小区', exact: true }).click()
  await page.getByRole('button', { name: '设施社区评分', exact: true }).click()
  await expect(page.getByText('6/7 已完成')).toBeVisible()
  await expect(page.locator('.scorecard__ring strong')).toHaveText('—')
  if (!await page.locator('.community-charts').evaluate((el: HTMLDetailsElement) => el.open)) await page.locator('.community-charts > summary').click()
  await expect(page.getByRole('img', { name: /服务覆盖雷达图/ })).toHaveAttribute('aria-label', /养老待查明/)
  await expect(page.locator('.coverage-radar__value')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '查看养老覆盖' })).toBeDisabled()
})
