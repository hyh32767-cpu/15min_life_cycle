import { expect, test } from '@playwright/test'
import { mockApi, setupRoute, openFavorites, pickFavorite, openPlan } from './mocks'

test.use({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true })

test('map creation saves an independent favorite through reload', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  const before = await page.locator('.endpoint').first().textContent()
  await pickFavorite(page)
  await expect(page.getByLabel('所选地点名称')).toHaveValue('构造验收地址')
  await page.getByLabel('所选地点名称').fill('地图新地点')
  await page.getByRole('button', { name: '确认位置', exact: true }).click()
  const library = page.getByRole('dialog', { name: '我的收藏', exact: true })
  await expect(library.locator('.favorite-place-row')).toContainText('地图新地点')
  await expect(page.locator('.endpoint').first()).toHaveText(before!)
  await page.reload()
  await openFavorites(page)
  await library.getByRole('button', { name: '设起点', exact: true }).click()
  await library.locator('.favorite-place-row').filter({ hasText: '地图新地点' }).getByRole('button').first().click()
  await expect(page.locator('.endpoint').first()).toContainText('地图新地点')
})

test('save independent places then create a named route from the library', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  const before = await page.locator('.endpoint').first().textContent()
  const library = await openFavorites(page)
  for (const query of ['图书馆', '公园']) {
    await library.getByRole('button', { name: '＋ 添加收藏', exact: true }).click()
    const add = page.getByRole('dialog', { name: '添加收藏', exact: true })
    await add.getByRole('searchbox').fill(query)
    await add.getByRole('button', { name: '搜索', exact: true }).click()
    await add.getByRole('button', { name: `收藏 ${query}候选`, exact: true }).click()
    await expect(library.locator('.favorite-place-row').filter({ hasText: query })).toBeVisible()
  }
  await expect(page.locator('.endpoint').first()).toHaveText(before!)
  await library.getByRole('tab', { name: /^路线 / }).click()
  await library.locator('.favorite-route-create > summary').click()
  await library.getByLabel('收藏路线起点').selectOption({ label: '图书馆候选' })
  await library.getByLabel('收藏路线终点').selectOption({ label: '公园候选' })
  await library.getByLabel('收藏路线名称').fill('周末路径')
  await library.getByRole('button', { name: '从收藏地点创建路线', exact: true }).click()
  await library.locator('.favorite-route-row').filter({ hasText: '周末路径' }).getByRole('button').first().click()
  await expect(page.locator('.endpoint').first()).toContainText('图书馆候选')
  await expect(page.locator('.endpoint').nth(1)).toContainText('公园候选')
  await page.reload()
  await openFavorites(page, 'routes')
  await expect(library.locator('.favorite-route-row')).toContainText('周末路径')
  await library.getByRole('tab', { name: /^地点 / }).click()
  await library.getByRole('button', { name: '删除收藏地点 图书馆候选', exact: true }).click()
  await expect(library.locator('.favorite-place-row')).toHaveCount(1)
  await page.reload()
  await openFavorites(page)
  await expect(library.locator('.favorite-place-row')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})

test('combined stay duration and shared departure settings are used by multi-stop planning', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await page.getByRole('button', { name: '出发设置', exact: true }).click()
  await page.getByLabel('出发时间', { exact: true }).fill('17:20')
  await page.getByLabel('最晚到达', { exact: true }).fill('18:50')
  await page.getByLabel('停留时间（分钟）', { exact: true }).fill('12')
  await expect(page.getByLabel('排队用时（分钟）', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '更新路径', exact: true }).click()
  await page.locator('.poi-main').first().click()
  await page.getByRole('button', { name: '加入今天安排', exact: true }).click()
  await openPlan(page)
  const dialog = page.getByRole('dialog', { name: '今天安排' })
  await expect(dialog).toContainText('17:20 出发')
  await expect(dialog).toContainText('18:50')
  const request = page.waitForRequest(r => r.method() === 'POST' && new URL(r.url()).pathname === '/api/plans')
  await dialog.getByRole('button', { name: '重新规划', exact: true }).click()
  const body = (await request).postDataJSON()
  expect(body.departureSeconds).toBe(62400)
  expect(body.deadlineSeconds).toBe(67800)
  expect(body.tasks[0].options[0].serviceSeconds).toBe(720)
})

test('expanded POI categories use their real keyword in the corridor request', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await expect(page.locator('.poi-main').first()).toBeVisible()
  await page.getByRole('button', { name: '更多类别', exact: true }).click()
  await expect(page.locator('.category-group')).toHaveCount(4)
  await expect(page.getByRole('button', { name: '展开或收起面板', exact: true })).toHaveAttribute('aria-expanded', 'true')
  const request = page.waitForRequest(r => r.method() === 'POST' && new URL(r.url()).pathname === '/api/pois/corridor')
  await page.getByRole('button', { name: '医院', exact: true }).click()
  expect((await request).postDataJSON().queryTerms).toEqual(['医院'])
  await expect(page.getByRole('button', { name: '医院', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.more-categories')).toHaveCount(0)
})
