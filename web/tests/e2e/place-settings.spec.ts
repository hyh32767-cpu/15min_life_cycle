import { expect, test } from '@playwright/test'
import { mockApi, setupRoute } from './mocks'

test.use({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true })

test('map creation exposes an unblocked confirmation and saves the point through reload', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await page.getByRole('button', { name: '我的地点', exact: true }).click()
  const library = page.getByRole('region', { name: '我的地点', exact: true })
  await library.getByRole('textbox', { name: '保存地点名称' }).fill('地图新地点')
  await library.getByRole('button', { name: '地图创建', exact: true }).click()
  await expect(page.getByRole('button', { name: '取消选点', exact: true })).toBeVisible()
  await page.locator('.baidu-map__container').click({ position: { x: 80, y: 200 } })
  await expect(page.getByRole('button', { name: '取消选点', exact: true })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: '所选地点名称' })).toHaveValue('构造验收地址')
  await page.getByRole('button', { name: '确认位置', exact: true }).click()
  await expect(library.getByRole('button', { name: '将 地图新地点 设为起点', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认位置', exact: true })).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: '我的地点', exact: true }).click()
  await expect(library.getByRole('button', { name: '将 地图新地点 设为起点', exact: true })).toBeVisible()
  await library.getByRole('button', { name: '将 地图新地点 设为起点', exact: true }).click()
  await expect(page.locator('.endpoint').first()).toContainText('地图新地点')
})

test('save independent places then create a named route from the library', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await expect(page.locator('.poi-main').first()).toBeVisible()
  const before = await page.locator('.endpoint').first().textContent()
  await page.getByRole('button', { name: '我的地点', exact: true }).click()
  const library = page.getByRole('region', { name: '我的地点', exact: true })
  for (const [query, label] of [['图书馆', '读书'], ['公园', '散步']]) {
    await library.getByRole('textbox', { name: '查找保存地点', exact: true }).fill(query)
    await library.getByRole('textbox', { name: '保存地点名称', exact: true }).fill(label)
    await library.getByRole('button', { name: '搜索', exact: true }).click()
    await library.getByRole('button', { name: '保存搜索地点 ' + query + '候选', exact: true }).click()
  }
  await expect(library.getByText('读书', { exact: true }).first()).toBeVisible()
  await expect(library.getByText('散步', { exact: true }).first()).toBeVisible()
  await expect(page.locator('.endpoint').first()).toHaveText(before!)
  await library.getByRole('combobox', { name: '已保存路径起点' }).selectOption({ label: '读书' })
  await library.getByRole('combobox', { name: '已保存路径终点' }).selectOption({ label: '散步' })
  await library.getByRole('textbox', { name: '新建路径名称' }).fill('周末路径')
  await library.getByRole('button', { name: '创建并使用路径', exact: true }).click()
  await expect(library).toHaveCount(0)
  await expect(page.locator('.endpoint').first()).toContainText('读书')
  await expect(page.locator('.endpoint').nth(1)).toContainText('散步')
  await page.reload()
  await page.getByRole('button', { name: '我的路径', exact: true }).click()
  await expect(page.locator('.results')).toContainText('周末路径')
  await page.getByRole('button', { name: '我的地点', exact: true }).click()
  await library.getByRole('button', { name: '删除保存地点 读书', exact: true }).click()
  await expect(library.getByRole('button', { name: '将 读书 设为起点', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})

test('combined stay duration and shared departure settings are used by multi-stop planning', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await page.getByRole('button', { name: '出发设置', exact: true }).click()
  await page.getByLabel('出发时间', { exact: true }).fill('17:20')
  await page.getByLabel('最晚到达', { exact: true }).fill('18:50')
  await page.getByLabel('停留时间（分钟）', { exact: true }).fill('12')
  await expect(page.getByLabel('排队用时（分钟）', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '更新路径', exact: true }).click()
  await page.locator('.poi-main').first().click()
  await page.getByRole('button', { name: '加入今天安排', exact: true }).click()
  await page.locator('.plan-bar').click()
  const dialog = page.getByRole('dialog', { name: '今天安排' })
  await expect(dialog).toContainText('17:20 出发')
  await expect(dialog).toContainText('18:50')
  const request = page.waitForRequest(r => r.method() === 'POST' && new URL(r.url()).pathname === '/api/plans')
  await dialog.getByRole('button', { name: '规划行程', exact: true }).click()
  const body = (await request).postDataJSON()
  expect(body.departureSeconds).toBe(62400)
  expect(body.deadlineSeconds).toBe(67800)
  expect(body.tasks[0].options[0].serviceSeconds).toBe(720)
})

test('expanded POI categories use their real keyword in the corridor request', async ({ page }) => {
  await mockApi(page)
  await setupRoute(page)
  await expect(page.locator('.poi-main').first()).toBeVisible()
  await page.getByRole('button', { name: '更多类别', exact: true }).click()
  await expect(page.locator('.category-group')).toHaveCount(4)
  await expect(page.getByRole('button', { name: '展开或收起面板', exact: true })).toHaveAttribute('aria-expanded', 'true')
  const request = page.waitForRequest(r => r.method() === 'POST' && new URL(r.url()).pathname === '/api/pois/corridor')
  await page.getByRole('button', { name: '医院', exact: true }).click()
  expect((await request).postDataJSON().queryTerms).toEqual(['医院'])
  await expect(page.getByRole('button', { name: '医院', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.more-categories')).toHaveCount(0)
})
