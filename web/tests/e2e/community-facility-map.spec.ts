import { expect, test } from '@playwright/test'
import { mockApi } from './mocks'

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })

test('selected service shows clickable facilities, switches cleanly and removes covered sample markers', async ({ page }) => {
  await mockApi(page)
  await page.route('**/api/pois/corridor', route => {
    const body = route.request().postDataJSON()
    const pois = body.category === '养老' ? [] : [{ place: { uid: `${body.category}-1`, name: `${body.category}测试店`,
      address: '测试街道8号', coord: body.routeGeometry[0], tags: body.queryTerms, source: 'synthetic-assumption' }, distanceToRouteM: 0 }]
    return route.fulfill({ json: { pois, retrieval: { truncated: false }, warnings: [] } })
  })
  let routeCalls = 0
  page.on('request', r => { if (r.url().endsWith('/api/routes/walking')) routeCalls++ })
  await page.goto('/community')
  await page.locator('.shell__search').click()
  await page.getByRole('searchbox').fill('回龙观')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('button', { name: '选择 回龙观小区', exact: true }).click()
  await expect(page.getByText('7/7 已完成')).toBeVisible()
  await page.getByRole('button', { name: '查看药店覆盖' }).click()
  const map = page.locator('.baidu-map__container')
  const pharmacy = map.getByRole('button', { name: '药店测试店 · 药店 · 参评设施', exact: true })
  await expect(pharmacy).toBeVisible()
  await expect(map.getByRole('img', { name: /已覆盖/ })).toHaveCount(0)
  await expect(page.getByText(/已选择药店；/)).toHaveCount(0)
  await expect(page.getByText(/部分类别未完成：/)).toHaveCount(0)
  await pharmacy.click()
  const card = page.getByRole('region', { name: '生活圈设施详情' })
  await expect(card).toContainText('药店测试店')
  await expect(card).toContainText('测试街道8号')
  await expect(page.locator('.origin-name')).toHaveText('回龙观小区')
  await expect(page.getByRole('dialog', { name: '确认地图地点' })).toHaveCount(0)
  expect(routeCalls).toBe(0)
  await card.getByRole('button', { name: '从圈中心步行到这里' }).click()
  await expect(page.getByRole('region', { name: '地图地点路线' })).toContainText('药店测试店')
  expect(routeCalls).toBe(1)
  await page.getByRole('button', { name: '查看早餐覆盖' }).click()
  await expect(pharmacy).toHaveCount(0)
  await expect(card).toHaveCount(0)
  await expect(page.getByRole('region', { name: '地图地点路线' })).toHaveCount(0)
  const breakfast = map.getByRole('button', { name: '早餐测试店 · 早餐 · 参评设施', exact: true })
  await expect(breakfast).toBeVisible()
  await breakfast.click()
  await expect(card).toContainText('早餐测试店')
  await card.getByRole('button', { name: '关闭设施详情' }).click()
  await expect(card).toHaveCount(0)
  await page.getByRole('button', { name: '查看养老覆盖' }).click()
  await expect(breakfast).toHaveCount(0)
  await page.getByRole('button', { name: '查看未覆盖位置', exact: true }).click()
  await expect(map.getByRole('img', { name: /未覆盖/ }).first()).toBeVisible()
  await page.locator('.shell__search').click()
  await page.getByRole('searchbox').fill('另一处位置')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('button', { name: '选择 另一处位置候选', exact: true }).click()
  await expect(map.getByRole('img', { name: /未覆盖/ })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
